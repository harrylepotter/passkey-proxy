import { randomBytes } from 'node:crypto';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

export async function checkPersistentLinks({ owner, agentContext, api, ownerToken, externalCredential, chosenSite, dir, observe, restart }) {
  await owner.getByLabel('Website account', { exact: true }).selectOption(externalCredential.id);
  await owner.getByLabel('Website to open').fill(chosenSite);
  await owner.locator('#local-preview').check();
  await owner.locator('#reusable-link').check();
  await owner.getByLabel('Link label', { exact: true }).fill('Repeat-access fixture');
  await owner.getByRole('button', { name: 'Create agent link' }).click();
  await owner.waitForFunction(() => document.querySelector('#open-agent').href.includes('#link='));
  const url = await owner.locator('#open-agent').getAttribute('href');
  const secret = new URLSearchParams(new URL(url).hash.slice(1)).get('link');
  assert.ok(secret);
  const instructions = await owner.locator('#invite-text').inputValue();
  assert.ok(instructions.includes('reuse this link')); assert.ok(instructions.includes('new approval'));
  const disk = readFileSync(join(dir, 'agent-links.json'), 'utf8');
  assert.ok(!disk.includes(secret));
  assert.equal((await api('/api/owner/state', secret)).status, 401);
  const page = await agentContext.newPage(); observe(page); await page.goto(url);
  await page.getByLabel('Agent name', { exact: true }).fill('Repeat fixture agent');
  await page.getByLabel('What do you need access for?').fill('First access');
  const firstOptions = { challenge: randomBytes(32).toString('base64url'), rpId: 'example.test', userVerification: 'required' };
  await page.getByLabel('Website WebAuthn request options').fill(JSON.stringify(firstOptions));
  await page.getByRole('button', { name: 'Request passkey approval' }).click();
  await page.getByRole('heading', { name: 'Waiting for approval' }).waitFor();
  const firstToken = await page.evaluate(() => sessionStorage.getItem('request-token'));
  const first = await (await api('/api/agent/request', firstToken)).json();
  assert.equal(first.requestNumber, 1);
  const duplicate = await api('/api/agent/requests', secret, { agent: 'Retry', purpose: 'Retry', ceremony: { origin: 'https://login.example.test', options: firstOptions } });
  assert.equal(duplicate.status, 200);
  const resumed = await duplicate.json(); assert.equal(resumed.created, false); assert.equal(resumed.accessToken, firstToken);
  assert.equal((await api('/api/agent/redeem', firstToken, {})).status, 400);
  assert.equal((await api(`/api/owner/requests/${first.id}/approve`, ownerToken, { passphrase: 'a-demo-only-passphrase-2026' })).status, 200);
  await page.getByRole('button', { name: 'Collect passkey response once' }).click();
  await page.getByRole('button', { name: 'Request another login' }).waitFor();
  await page.getByRole('button', { name: 'Request another login' }).click();
  await page.getByLabel('What do you need access for?').fill('Website session expired; approve a fresh login.');
  await page.getByLabel('Website WebAuthn request options').fill(JSON.stringify({ ...firstOptions, challenge: randomBytes(32).toString('base64url') }));
  await page.getByRole('button', { name: 'Request passkey approval' }).click();
  await page.getByText('Wait one minute between new access requests on this link.', { exact: true }).waitFor();
  console.log('PASS persistent link creation, private storage, duplicate-request recovery, first approval and renewal cooldown');
  // Exercise the real server clock and browser renewal without a test-only bypass.
  await new Promise(resolve => setTimeout(resolve, Math.max(0, first.createdAt + 60_100 - Date.now())));
  await page.getByRole('button', { name: 'Request passkey approval' }).click();
  await page.getByRole('heading', { name: 'Waiting for approval' }).waitFor();
  const secondToken = await page.evaluate(() => sessionStorage.getItem('request-token'));
  const second = await (await api('/api/agent/request', secondToken)).json();
  assert.equal(second.requestNumber, 2); assert.notEqual(secondToken, firstToken);
  assert.equal((await api('/api/agent/redeem', secondToken, {})).status, 400);
  assert.equal((await api('/api/agent/redeem', firstToken, {})).status, 400);
  await owner.locator(`input[data-passphrase="${second.id}"]`).fill('a-demo-only-passphrase-2026');
  await owner.locator(`button[data-id="${second.id}"][data-action="approve"]`).click();
  await page.getByRole('button', { name: 'Collect passkey response once' }).waitFor();
  // Revoke a ready handoff through the owner's UI; the agent must lose collection.
  await owner.locator('#agent-links').getByRole('button', { name: 'Revoke link' }).click();
  await page.getByRole('heading', { name: 'Access was declined' }).waitFor();
  assert.equal((await api('/api/agent/redeem', secondToken, {})).status, 400);
  assert.equal((await api('/api/agent/config', secret)).status, 400);
  assert.equal((await api('/api/agent/requests', secret, { agent: 'Agent', purpose: 'Revoked' })).status, 400);
  const live = await (await api('/api/owner/invites', ownerToken, { credentialId: externalCredential.id, site: chosenSite, reusable: true, localPreview: true, label: 'Restart fixture' })).json();
  const liveSecret = new URLSearchParams(new URL(live.url).hash.slice(1)).get('link');
  await page.goto(live.url); await page.getByLabel('Agent name', { exact: true }).fill('Restart fixture');
  await page.getByLabel('Website WebAuthn request options').fill(JSON.stringify({ ...firstOptions, challenge: randomBytes(32).toString('base64url') }));
  await page.getByLabel('What do you need access for?').fill('Survive restart'); await page.getByRole('button', { name: 'Request passkey approval' }).click();
  await page.getByRole('heading', { name: 'Waiting for approval' }).waitFor();
  await api('/api/owner/agent-origin', ownerToken, { origin: 'https://agent.example.test' });
  await restart();
  const state = await (await api('/api/owner/state', ownerToken)).json();
  assert.equal(state.vault.unlocked, false); assert.equal(state.agentAccess.publicOrigin, 'https://agent.example.test');
  assert.equal(state.links.find(link => link.id === first.linkId).revokedAt !== null, true);
  assert.equal((await (await api('/api/agent/config', liveSecret)).json()).reusable, true);
  assert.equal((await api('/api/agent/config', secret)).status, 400);
  await page.getByRole('button', { name: 'Request passkey approval' }).waitFor();
  await page.getByText('The previous request is no longer available. Submit a new request using this same link.', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => sessionStorage.getItem('request-token')), null);
  assert.equal((await api('/api/owner/links/' + live.link.id + '/revoke', liveSecret, {})).status, 401);
  assert.equal((await fetch('http://127.0.0.1:4872/api/owner/links/' + live.link.id + '/revoke', { method: 'POST', headers: { Authorization: `Bearer ${ownerToken}`, 'Content-Type': 'application/json' }, body: '{}' })).status, 404);
  await api('/api/owner/agent-origin', ownerToken, { origin: '' });
  await page.close();
  console.log('PASS repeat approval, revocation before collection, durable links/counters/revocation/origin, restart recovery and private owner controls');
}
